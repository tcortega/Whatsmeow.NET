// Command check-repo stops source and project files from switching a build rule off, by accident or for
// convenience, where no analyzer can see it. Reviewers judge intent; this only keeps the defaults in place.
//
// It prefers allowlists: only the blessed analyzer configs, MSBuild infrastructure files, csproj elements,
// generated folders and Go build tags exist; anything else is reported, and the fix for a real need is to
// extend the allowlist here in a reviewed change. On top of that it rejects, in C# outside generated code:
// unjustified pragmas and SuppressMessage attributes, generated-code markers, aliases of the suppression and
// generated-code attributes, captured contexts, positional records, and a [LoggerMessage] event id that another log
// line of a shipped assembly has. In YAML under .github/ (workflows and
// composite actions) and in shell scripts it rejects any step that deletes a GitHub release: a release holds the
// Corresponding Source of the packages on nuget.org, which stay there, so it is never deleted (ADR 0016, ADR 0029).
// In the README, the user guides and the packages' READMEs, a code block under a snippet marker must be the sample
// file it names, byte for byte, so the code they show is code CI builds (ADR 0054).
// In the stable packages' PublicAPI files it rejects a *REMOVED* line, which would let a build drop a shipped member,
// a generated protobuf or gRPC type outside the [WMN1001] Raw hatch, and in it any but an upstream WhatsApp one
// (ARCHITECTURE §13 invariant 6, ADR 0055). A package validation suppression file may only accept a member added to
// IWhatsAppClient or a change of the Raw hatch, so no other break hides from the comparison with the last release.
//
// Findings print as path:line: [rule] message. The rules are in docs/guidelines/csharp.md Suppressions.
// Run it from the tools module: go -C tools run ./check-repo [-root ..].
