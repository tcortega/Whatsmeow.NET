// Command check-repo stops source and project files from switching a build rule off, by accident or for
// convenience, where no analyzer can see it. Reviewers judge intent; this only keeps the defaults in place.
//
// It prefers allowlists: only the blessed analyzer configs, MSBuild infrastructure files, csproj elements,
// generated folders and Go build tags exist; anything else is reported, and the fix for a real need is to
// extend the allowlist here in a reviewed change. On top of that it rejects, in C# outside generated code:
// unjustified pragmas and SuppressMessage attributes, generated-code markers, aliases of the suppression and
// generated-code attributes, captured contexts, and positional records.
//
// Findings print as path:line: [rule] message. The rules are in docs/guidelines/csharp.md Suppressions.
// Run it from the tools module: go -C tools run ./check-repo [-root ..].
package main

import (
	"bufio"
	"bytes"
	"context"
	"encoding/xml"
	"errors"
	"flag"
	"fmt"
	"go/build/constraint"
	"io"
	"io/fs"
	"os"
	"os/signal"
	"path"
	"regexp"
	"slices"
	"strings"
)

const extendAllowlist = "extend the allowlist in tools/check-repo in a reviewed change"

// generatedDirs are the folders a buf template with clean: true writes and CI regenerates and diffs.
// A folder is blessed only once CI regenerates it (#3 adds dotnet/src/Whatsmeow.Protocol/Generated/ and sidecar/gen/).
func generatedDirs() []string {
	return []string{"dotnet/src/Whatsmeow.Protocol.WhatsApp/Generated/"}
}

// blessedFiles are the only files of each kind that may exist; any other file with the same name is a finding.
func blessedFiles() map[string][]string {
	return map[string][]string{
		"analyzer-config": {".editorconfig", "dotnet/.globalconfig"},
		"msbuild-infra":   {"dotnet/Directory.Build.props", "dotnet/Directory.Build.targets", "dotnet/src/Directory.Build.props", "dotnet/Directory.Packages.props"},
		"nuget-config":    {"nuget.config"},
		"global-json":     {"global.json"},
	}
}

// skippedDirs hold version control state and build output, never our source.
func skippedDirs() []string {
	return []string{".git", "dotnet/artifacts"}
}

var (
	msbuildInfraName  = regexp.MustCompile(`(?i)^Directory\.[^/]*\.(?:props|targets|rsp)$`)
	generatedFileName = regexp.MustCompile(`(?i)(?:\.g\.i\.cs|\.g\.cs|\.generated\.cs|\.designer\.cs)$|^TemporaryGeneratedFile_`)
	pragmaDisable     = regexp.MustCompile(`^\s*#\s*pragma\s+warning\s+disable\b([^/]*)`)
	pragmaRuleID      = regexp.MustCompile(`^\s+[A-Za-z]*[0-9]+\b`)
	nullableDisable   = regexp.MustCompile(`^\s*#\s*nullable\s+disable\b`)
	justification     = regexp.MustCompile(`//\s*Justification:\s*\S`)
	autoGenerated     = regexp.MustCompile(`(?i)<auto-?generated`)
	goGenerated       = regexp.MustCompile(`^// Code generated .* DO NOT EDIT\.$`)
	suppressMessage   = regexp.MustCompile(`\b(?:Unconditional)?SuppressMessage(?:Attribute)?\s*\(`)
	justificationArg  = regexp.MustCompile(`\bJustification\s*=\s*"\s*x`)
	generatedCodeAttr = regexp.MustCompile(`\bGeneratedCode(?:Attribute)?\s*\(`)
	attributeAlias    = regexp.MustCompile(`\busing\s+[A-Za-z_]\w*\s*=\s*[\w.:\s]*\b(?:GeneratedCode|(?:Unconditional)?SuppressMessage)(?:Attribute)?\s*;`)
	capturedContext   = regexp.MustCompile(`\bConfigureAwait\s*\(\s*(?:continueOnCapturedContext\s*:\s*)?true\s*\)|\bContinueOnCapturedContext\b`)
	positionalRecord  = regexp.MustCompile(`\brecord\s+(?:struct\s+|class\s+)?[A-Za-z_]\w*\s*(?:<[^>]*>)?\s*\(`)
)

var errFindings = errors.New("repository check failed")

func main() {
	root := flag.String("root", "..", "the repository root")
	flag.Parse()

	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt)
	err := run(ctx, os.DirFS(*root), os.Stdout)
	stop()
	if err != nil {
		fmt.Fprintln(os.Stderr, "check-repo:", err)
		os.Exit(1)
	}
}

func run(ctx context.Context, fsys fs.FS, out io.Writer) error {
	findings, err := check(ctx, fsys)
	if err != nil {
		return err
	}

	for _, f := range findings {
		_, err = fmt.Fprintln(out, f)
		if err != nil {
			return fmt.Errorf("report: %w", err)
		}
	}

	if len(findings) > 0 {
		return fmt.Errorf("%w: %d findings (docs/guidelines/csharp.md Suppressions)", errFindings, len(findings))
	}

	return nil
}

// finding is one rule violation at a line (0 when it is about the whole file).
type finding struct {
	path    string
	line    int
	rule    string
	message string
}

func (f finding) String() string {
	return fmt.Sprintf("%s:%d: [%s] %s", f.path, f.line, f.rule, f.message)
}

func check(ctx context.Context, fsys fs.FS) ([]finding, error) {
	var findings []finding

	err := fs.WalkDir(fsys, ".", func(name string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}

		if ctx.Err() != nil {
			return fmt.Errorf("walk: %w", ctx.Err())
		}

		if entry.IsDir() {
			if isSkipped(name) {
				return fs.SkipDir
			}

			return nil
		}

		found, err := checkFile(fsys, name)
		if err != nil {
			return err
		}

		findings = append(findings, found...)

		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("walk the repository: %w", err)
	}

	return findings, nil
}

func isSkipped(name string) bool {
	base := path.Base(name)
	if base == "bin" || base == "obj" || base == "node_modules" {
		return true
	}

	return slices.Contains(skippedDirs(), name)
}

func isGenerated(name string) bool {
	return slices.ContainsFunc(generatedDirs(), func(dir string) bool { return strings.HasPrefix(name, dir) })
}

func checkFile(fsys fs.FS, name string) ([]finding, error) {
	if f, ok := checkName(name); ok {
		return []finding{f}, nil
	}

	ext := strings.ToLower(path.Ext(name))
	if ext != ".cs" && ext != ".go" && ext != ".csproj" {
		return nil, nil
	}

	if isGenerated(name) {
		return nil, nil
	}

	content, err := fs.ReadFile(fsys, name)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", name, err)
	}

	switch ext {
	case ".cs":
		return checkCSharp(name, content), nil
	case ".go":
		return checkGo(name, content), nil
	default:
		return checkProject(name, content), nil
	}
}

// checkName reports a file whose name alone breaks a rule: a configuration file that is not the blessed one,
// or a generated-code file name.
func checkName(name string) (finding, bool) {
	base := path.Base(name)
	lower := strings.ToLower(base)

	kind := ""

	switch {
	case lower == ".editorconfig" || strings.HasSuffix(lower, ".globalconfig"):
		kind = "analyzer-config"
	case msbuildInfraName.MatchString(base):
		kind = "msbuild-infra"
	case strings.HasSuffix(lower, ".rsp") || strings.HasSuffix(lower, ".ruleset"):
		return finding{name, 0, "msbuild-infra", "response files and rule sets switch compiler and analyzer options; " + extendAllowlist}, true
	case lower == "nuget.config":
		kind = "nuget-config"
	case lower == "global.json":
		kind = "global-json"
	}

	if kind != "" {
		if slices.Contains(blessedFiles()[kind], name) {
			return finding{}, false
		}

		return finding{name, 0, kind, "only " + strings.Join(blessedFiles()[kind], ", ") + " may exist; " + extendAllowlist}, true
	}

	if strings.HasSuffix(lower, ".cs") && generatedFileName.MatchString(base) && !isGenerated(name) {
		return finding{name, 0, "generated", "generated-code file name outside the folders CI regenerates"}, true
	}

	return finding{}, false
}

func checkCSharp(name string, content []byte) []finding {
	var findings []finding

	leading := true

	for number, line := range lines(content) {
		trimmed := strings.TrimSpace(line)
		if leading && trimmed != "" && !strings.HasPrefix(trimmed, "//") && !strings.HasPrefix(trimmed, "/*") && !strings.HasPrefix(trimmed, "*") {
			leading = false
		}

		// Roslyn treats a file as generated when its leading comments carry the marker.
		if leading && autoGenerated.MatchString(line) {
			findings = append(findings, finding{name, number, "generated", "generated-code marker outside the folders CI regenerates; analyzers would skip this file"})
		}

		if match := pragmaDisable.FindStringSubmatch(line); match != nil {
			if !pragmaRuleID.MatchString(match[1]) {
				findings = append(findings, finding{name, number, "pragma", "name the rule IDs it disables"})
			}

			if !justification.MatchString(line) {
				findings = append(findings, finding{name, number, "pragma", "add \"// Justification: <why>\" on the same line"})
			}
		}

		if nullableDisable.MatchString(line) && !justification.MatchString(line) {
			findings = append(findings, finding{name, number, "pragma", "add \"// Justification: <why>\" on the same line"})
		}
	}

	code := stripCSharp(content)

	for _, at := range suppressMessage.FindAllIndex(code, -1) {
		args := balancedArgs(code[at[1]-1:])
		if !justificationArg.Match(args) {
			findings = append(findings, finding{name, lineAt(code, at[0]), "suppress-message", "set a non-empty Justification = \"<why>\""})
		}
	}

	for _, rule := range []struct {
		pattern *regexp.Regexp
		rule    string
		message string
	}{
		{generatedCodeAttr, "generated", "[GeneratedCode] marks hand-written code as generated; analyzers would skip it"},
		{attributeAlias, "attribute-alias", "an alias of a suppression or generated-code attribute hides it from review and from this check"},
		{capturedContext, "captured-context", "library code never resumes on the caller's context; use ConfigureAwait(false)"},
		{positionalRecord, "positional-record", "records use required init members, not a primary constructor (VSA0002)"},
	} {
		for _, at := range rule.pattern.FindAllIndex(code, -1) {
			findings = append(findings, finding{name, lineAt(code, at[0]), rule.rule, rule.message})
		}
	}

	slices.SortStableFunc(findings, func(a, b finding) int { return a.line - b.line })

	return findings
}

// stripCSharp blanks comments and string contents, keeping every newline so offsets map to the same lines.
// Inside a string literal each non-space character becomes x, so "" and "why" stay distinguishable.
// Interpolation holes are treated as string content.
func stripCSharp(src []byte) []byte {
	out := bytes.Clone(src)

	blank := func(from, to int, fill byte) {
		for i := from; i < to && i < len(out); i++ {
			if out[i] == '\n' || out[i] == '\r' {
				continue
			}

			if fill == ' ' || out[i] == ' ' || out[i] == '\t' {
				out[i] = ' '

				continue
			}

			out[i] = fill
		}
	}

	for i := 0; i < len(src); {
		switch {
		case bytes.HasPrefix(src[i:], []byte("//")):
			end := bytes.IndexByte(src[i:], '\n')
			if end < 0 {
				end = len(src) - i
			}

			blank(i, i+end, ' ')
			i += end
		case bytes.HasPrefix(src[i:], []byte("/*")):
			end := bytes.Index(src[i+2:], []byte("*/"))
			if end < 0 {
				end = len(src) - i - 2
			}

			blank(i, i+2+end+2, ' ')
			i += 2 + end + 2
		case src[i] == '"' || ((src[i] == '@' || src[i] == '$') && stringStartsAt(src, i)):
			i = skipString(src, i, blank)
		case src[i] == '\'':
			end := i + 1
			for end < len(src) && src[end] != '\'' && src[end] != '\n' {
				if src[end] == '\\' {
					end++
				}

				end++
			}

			blank(i+1, end, 'x')
			i = end + 1
		default:
			i++
		}
	}

	return out
}

// stringStartsAt reports whether a string literal with @ or $ prefixes starts at i.
func stringStartsAt(src []byte, i int) bool {
	for i < len(src) && (src[i] == '@' || src[i] == '$') {
		i++
	}

	return i < len(src) && src[i] == '"'
}

// skipString blanks the string literal at i (regular, verbatim, interpolated or raw) and returns the index after it.
func skipString(src []byte, i int, blank func(from, to int, fill byte)) int {
	verbatim := false
	for src[i] == '@' || src[i] == '$' {
		verbatim = verbatim || src[i] == '@'
		i++
	}

	quotes := 0
	for i+quotes < len(src) && src[i+quotes] == '"' {
		quotes++
	}

	if quotes >= 3 {
		closing := bytes.Repeat([]byte{'"'}, quotes)
		end := bytes.Index(src[i+quotes:], closing)
		if end < 0 {
			end = len(src) - i - quotes
		}

		blank(i+quotes, i+quotes+end, 'x')

		return i + quotes + end + quotes
	}

	j := i + 1
	for j < len(src) {
		switch {
		case verbatim && src[j] == '"' && j+1 < len(src) && src[j+1] == '"':
			j += 2

			continue
		case !verbatim && src[j] == '\\':
			j += 2

			continue
		case src[j] == '"':
			blank(i+1, j, 'x')

			return j + 1
		case !verbatim && src[j] == '\n':
			blank(i+1, j, 'x')

			return j
		}

		j++
	}

	blank(i+1, len(src), 'x')

	return len(src)
}

// balancedArgs returns the text from the opening parenthesis at code[0] to its matching close.
func balancedArgs(code []byte) []byte {
	depth := 0

	for i, c := range code {
		switch c {
		case '(':
			depth++
		case ')':
			depth--
			if depth == 0 {
				return code[:i+1]
			}
		}
	}

	return code
}

func lineAt(content []byte, offset int) int {
	return 1 + bytes.Count(content[:offset], []byte("\n"))
}

func checkGo(name string, content []byte) []finding {
	var findings []finding

	for number, line := range lines(content) {
		if goGenerated.MatchString(line) {
			findings = append(findings, finding{name, number, "generated", "generated-code marker outside the folders CI regenerates; golangci-lint would skip this file"})
		}

		if constraint.IsPlusBuild(line) {
			findings = append(findings, finding{name, number, "build-tag", "use //go:build, not // +build"})
		}

		if !constraint.IsGoBuild(line) {
			continue
		}

		expr, err := constraint.Parse(line)
		if err != nil {
			findings = append(findings, finding{name, number, "build-tag", "unparsable //go:build line"})

			continue
		}

		for _, tag := range tags(expr) {
			if !allowedTag(name, tag) {
				findings = append(findings, finding{name, number, "build-tag", fmt.Sprintf("build tag %q can hide code from build, test and lint; %s", tag, extendAllowlist)})
			}
		}
	}

	return findings
}

func tags(expr constraint.Expr) []string {
	switch e := expr.(type) {
	case *constraint.TagExpr:
		return []string{e.Tag}
	case *constraint.NotExpr:
		return tags(e.X)
	case *constraint.AndExpr:
		return append(tags(e.X), tags(e.Y)...)
	case *constraint.OrExpr:
		return append(tags(e.X), tags(e.Y)...)
	default:
		return nil
	}
}

// allowedTag accepts GOOS and GOARCH values, fakewhatsapp (reserved for the fake WhatsApp mode, #5), and ignore
// for helper programs under tools/.
func allowedTag(name, tag string) bool {
	platforms := []string{
		"aix", "android", "darwin", "dragonfly", "freebsd", "illumos", "ios", "js", "linux", "netbsd", "openbsd",
		"plan9", "solaris", "wasip1", "windows", "unix",
		"386", "amd64", "arm", "arm64", "loong64", "mips", "mips64", "mips64le", "mipsle", "ppc64", "ppc64le",
		"riscv64", "s390x", "wasm",
	}

	switch {
	case slices.Contains(platforms, tag), tag == "fakewhatsapp":
		return true
	case tag == "ignore":
		return strings.HasPrefix(name, "tools/")
	default:
		return false
	}
}

// projectRules is the csproj allowlist: the elements and properties the projects use now, plus what Phase 1
// obviously needs. Everything else is reported.
type projectRules struct {
	properties map[string]func(value string) bool
	items      map[string][]string
	metadata   map[string][]string
	includes   map[string][]string
}

func csprojRules() projectRules {
	anyValue := func(string) bool { return true }

	return projectRules{
		properties: map[string]func(string) bool{
			"OutputType":            anyValue,
			"IsPackable":            anyValue,
			"RootNamespace":         anyValue,
			"AssemblyName":          anyValue,
			"PublishAot":            anyValue,
			"TrimmerSingleWarn":     anyValue,
			"RuntimeIdentifiers":    anyValue,
			"RuntimeIdentifier":     anyValue,
			"TreatWarningsAsErrors": func(v string) bool { return strings.TrimSpace(v) == "true" },
		},
		items: map[string][]string{
			"PackageReference":    {"Include", "PrivateAssets"},
			"ProjectReference":    {"Include"},
			"Using":               {"Include", "Alias", "Static"},
			"InternalsVisibleTo":  {"Include"},
			"None":                {"Include", "Update", "CopyToOutputDirectory"},
			"Content":             {"Include", "Update", "CopyToOutputDirectory"},
			"AdditionalFiles":     {"Include"},
			"TrimmerRootAssembly": {"Include"},
		},
		metadata: map[string][]string{
			"None":    {"CopyToOutputDirectory"},
			"Content": {"CopyToOutputDirectory"},
		},
		includes: map[string][]string{
			"AdditionalFiles": {"PublicAPI.Shipped.txt", "PublicAPI.Unshipped.txt"},
		},
	}
}

func checkProject(name string, content []byte) []finding {
	rules := csprojRules()

	var findings []finding

	report := func(offset int64, what string) {
		findings = append(findings, finding{name, lineAt(content, int(offset)), "csproj", what + " is not in the csproj allowlist; " + extendAllowlist})
	}

	decoder := xml.NewDecoder(bytes.NewReader(content))

	var stack []string

	for {
		offset := decoder.InputOffset()

		token, err := decoder.Token()
		if errors.Is(err, io.EOF) {
			break
		}

		if err != nil {
			findings = append(findings, finding{name, lineAt(content, int(offset)), "csproj", "not well-formed XML: " + err.Error()})

			break
		}

		switch t := token.(type) {
		case xml.StartElement:
			checkElement(rules, stack, t, offset, report)
			stack = append(stack, t.Name.Local)
		case xml.EndElement:
			stack = stack[:len(stack)-1]
		case xml.CharData:
			if len(stack) == 3 && stack[0] == "Project" && stack[1] == "PropertyGroup" {
				if valid := rules.properties[stack[2]]; valid != nil && !valid(string(t)) {
					report(offset, fmt.Sprintf("<%s>%s</%s>", stack[2], strings.TrimSpace(string(t)), stack[2]))
				}
			}
		case xml.ProcInst, xml.Comment, xml.Directive:
		}
	}

	return findings
}

func checkElement(rules projectRules, stack []string, element xml.StartElement, offset int64, report func(int64, string)) {
	elementName := element.Name.Local
	attrs := map[string]string{}

	for _, a := range element.Attr {
		attrs[a.Name.Local] = a.Value
	}

	allowAttrs := func(allowed ...string) {
		for attr := range attrs {
			if !slices.Contains(allowed, attr) {
				report(offset, fmt.Sprintf("attribute %s on <%s>", attr, elementName))
			}
		}
	}

	switch len(stack) {
	case 0:
		if elementName != "Project" || attrs["Sdk"] != "Microsoft.NET.Sdk" {
			report(offset, fmt.Sprintf("<%s> as the root (only <Project Sdk=\"Microsoft.NET.Sdk\">)", elementName))
		}

		allowAttrs("Sdk")
	case 1:
		if elementName != "PropertyGroup" && elementName != "ItemGroup" {
			report(offset, "<"+elementName+">")

			return
		}

		allowAttrs("Condition", "Label")
	case 2:
		if stack[1] == "PropertyGroup" {
			if rules.properties[elementName] == nil {
				report(offset, "property <"+elementName+">")
			}

			allowAttrs("Condition")

			return
		}

		allowed, ok := rules.items[elementName]
		if !ok {
			report(offset, "item <"+elementName+">")

			return
		}

		allowAttrs(allowed...)

		if includes := rules.includes[elementName]; includes != nil && !slices.Contains(includes, attrs["Include"]) {
			report(offset, fmt.Sprintf("<%s Include=%q>", elementName, attrs["Include"]))
		}
	default:
		if len(stack) == 3 && stack[1] == "ItemGroup" && slices.Contains(rules.metadata[stack[2]], elementName) {
			return
		}

		report(offset, "<"+elementName+"> inside <"+strings.Join(stack[1:], "><")+">")
	}
}

// lines yields each line with its 1-based number, without the line ending. Lines of any length are read.
func lines(content []byte) func(yield func(int, string) bool) {
	return func(yield func(int, string) bool) {
		scanner := bufio.NewScanner(bytes.NewReader(content))
		scanner.Buffer(make([]byte, 0, 64*1024), len(content)+1)

		for number := 1; scanner.Scan(); number++ {
			if !yield(number, strings.TrimSuffix(scanner.Text(), "\r")) {
				return
			}
		}
	}
}
