func TestCheckFindsEveryRule(t *testing.T) {
	t.Parallel()

	repo := fstest.MapFS{
		".editorconfig":        {Data: []byte("root = true\n")},
		"dotnet/.globalconfig": {Data: []byte("is_global = true\n")},
		"dotnet/src/A/Pragma.cs": {Data: []byte("namespace A;\n" +
			"#pragma warning disable CA1822\n" +
			"#pragma warning disable CA1822 // Justification: the analyzer misreads the generated partial\n" +
			"#pragma warning disable CA1822 // Justification:\n" +
			"#nullable disable\n")},
		"dotnet/src/A/Suppress.cs": {Data: []byte("namespace A;\n" +
			"[SuppressMessage(\"Style\", \"IDE0001\")]\n" +
			"[SuppressMessage(\"Style\", \"IDE0002\", Justification = \"\")]\n" +
			"[System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage(\"Trimming\", \"IL2026\",\n" +
			"\tJustification = \"the member is preserved by DynamicDependency\")]\n" +
			"[assembly: SuppressMessage(\"Style\", \"IDE0003\",\n" +
			"\tScope = \"member\")]\n")},
		"dotnet/src/A/Marker.cs":                                       {Data: []byte("// <auto-generated/>\nnamespace A;\n[GeneratedCode(\"x\", \"1\")]\ninternal sealed class B;\n")},
		"dotnet/src/A/Widget.g.cs":                                     {Data: []byte("namespace A;\n")},
		"dotnet/src/A/Context.cs":                                      {Data: []byte("await x.ConfigureAwait(true);\nawait x.ConfigureAwait(ConfigureAwaitOptions.ContinueOnCapturedContext);\nawait x.ConfigureAwait(false);\n")},
		"dotnet/src/A/Records.cs":                                      {Data: []byte("public sealed record Point(int X);\npublic readonly record struct Id(string Value);\npublic record class Pair<T>(T A);\npublic sealed record Fine\n{\n}\n")},
		"dotnet/tests/T/.editorconfig":                                 {Data: []byte("[*.cs]\n")},
		"dotnet/src/A/Rules.globalconfig":                              {Data: []byte("is_global = true\n")},
		"sidecar/internal/x/x.go":                                      {Data: []byte("// Code generated by hand. DO NOT EDIT.\npackage x\n")},
		"sidecar/gen/whatsmeow/v1/a.pb.go":                             {Data: []byte("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage whatsmeowv1\n")},
		"dotnet/src/Whatsmeow.Protocol.WhatsApp/Generated/WACommon.cs": {Data: []byte("// <auto-generated>\n#pragma warning disable 1591\n")},
		"dotnet/artifacts/publish/X/Entry.cs":                          {Data: []byte("// <auto-generated/>\n#pragma warning disable\n")},
	}

	findings, err := check(context.Background(), repo)
	if err != nil {
		t.Fatalf("check: %v", err)
	}

	want := []string{
		"dotnet/src/A/Context.cs:1: [captured-context]",
		"dotnet/src/A/Context.cs:2: [captured-context]",
		"dotnet/src/A/Marker.cs:1: [generated]",
		"dotnet/src/A/Marker.cs:3: [generated]",
		"dotnet/src/A/Pragma.cs:2: [pragma]",
		"dotnet/src/A/Pragma.cs:4: [pragma]",
		"dotnet/src/A/Pragma.cs:5: [pragma]",
		"dotnet/src/A/Records.cs:1: [positional-record]",
		"dotnet/src/A/Records.cs:2: [positional-record]",
		"dotnet/src/A/Records.cs:3: [positional-record]",
		"dotnet/src/A/Rules.globalconfig:0: [analyzer-config]",
		"dotnet/src/A/Suppress.cs:2: [suppress-message]",
		"dotnet/src/A/Suppress.cs:3: [suppress-message]",
		"dotnet/src/A/Suppress.cs:6: [suppress-message]",
		"dotnet/src/A/Widget.g.cs:0: [generated]",
		"dotnet/tests/T/.editorconfig:0: [analyzer-config]",
		"sidecar/internal/x/x.go:1: [generated]",
	}

	got := make([]string, 0, len(findings))
	for _, f := range findings {
		got = append(got, fmt.Sprintf("%s:%d: [%s]", f.path, f.line, f.rule))
	}

	if len(got) != len(want) {
		t.Fatalf("got %d findings:\n%q\nwant %d:\n%q", len(got), got, len(want), want)
	}

	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("finding %d = %q, want %q\nall: %q", i, got[i], want[i], got)
		}
	}
}

func TestCheckCleanRepositoryHasNoFindings(t *testing.T) {
	t.Parallel()

	repo := fstest.MapFS{
		".editorconfig":        {Data: []byte("root = true\n")},
		"dotnet/.globalconfig": {Data: []byte("is_global = true\n")},
		"dotnet/src/A/Clean.cs": {Data: []byte("namespace A;\n\n" +
			"public sealed record Result\n{\n\tpublic required int Value { get; init; }\n}\n" +
			"// A comment about ConfigureAwait(false) and records.\n")},
	}

	var out bytes.Buffer

	err := run(context.Background(), repo, &out)
	if err != nil {
		t.Fatalf("run: %v, output %q", err, out.String())
	}
}

func TestRunFailsOnFindings(t *testing.T) {
	t.Parallel()

	repo := fstest.MapFS{"dotnet/src/A/Bad.cs": {Data: []byte("#pragma warning disable\n")}}

	var out bytes.Buffer

	err := run(context.Background(), repo, &out)
	if !errors.Is(err, errFindings) {
		t.Fatalf("run = %v, want errFindings", err)
	}

	if out.String() != "dotnet/src/A/Bad.cs:1: [pragma] add \"// Justification: <why>\" on the same line\n" {
		t.Fatalf("output = %q", out.String())
	}
}
